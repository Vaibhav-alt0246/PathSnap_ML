"""Interactive Folium map generation for PathSnap.

Renders authentic geographical maps displaying:
1. Observed GPS points and trajectory (blue).
2. Nearby candidate road segments (orange).
3. Metric perpendicular projection lines (red dashed).
4. Local road network arcs (grey).
5. Ground-truth reference route sequence (green, training only).
Includes layer controls and a responsive interactive legend.
"""

from pathlib import Path
from typing import Optional
import folium
import numpy as np
import pandas as pd

from member_a.config.settings import MAPS_DIR, TRAIN_PARTITION
from member_a.src.data.loader import Trip
from member_a.src.projection.projection import CoordinateProjector, get_utm_epsg_for_coords


def create_interactive_map(
    trip: Trip,
    candidates: pd.DataFrame,
    labeled_candidates: Optional[pd.DataFrame] = None,
    max_points: int = 120,
    out_html_path: Optional[Path] = None,
) -> Path:
    """Generate an interactive Folium HTML map for a trip.

    Parameters
    ----------
    trip : Trip
        The loaded trip dataclass.
    candidates : pd.DataFrame
        Candidate road segments generated by `generate_candidates`.
    labeled_candidates : Optional[pd.DataFrame]
        Optional DataFrame with training 'label' column.
    max_points : int
        Maximum number of GPS observations to render in full detail to maintain
        smooth 60fps browser interaction.
    out_html_path : Optional[Path]
        Target HTML output path. Defaults to `member_a/maps/trip_{trip_id}_map.html`.

    Returns
    -------
    Path
        The path of the written HTML map.
    """
    out_path = (
        out_html_path
        if out_html_path is not None
        else MAPS_DIR / f"trip_{trip.trip_id}_interactive_map.html"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)

    # 1. Trajectory subset for crisp map rendering
    track_subset = trip.track.iloc[:max_points].copy()
    cands_subset = candidates[candidates["point_idx"] < max_points].copy()

    # Center map on trajectory centroid
    center_lat = float(track_subset["lat"].mean())
    center_lon = float(track_subset["lon"].mean())

    fmap = folium.Map(
        location=[center_lat, center_lon],
        zoom_start=15,
        tiles="OpenStreetMap",
        control_scale=True,
    )

    # Feature Groups
    fg_network = folium.FeatureGroup(name="Local Road Network", show=True)
    fg_gps_track = folium.FeatureGroup(name="GPS Trajectory (Observed)", show=True)
    fg_candidates = folium.FeatureGroup(name="Candidate Road Segments", show=True)
    fg_projections = folium.FeatureGroup(name="Candidate Projections", show=False)
    fg_ground_truth = folium.FeatureGroup(name="Ground Truth Route (Train)", show=True)

    # Convert metric projected_x, projected_y back to lon/lat for projection lines
    med_lon = float(trip.track["lon"].median())
    med_lat = float(trip.track["lat"].median())
    epsg = get_utm_epsg_for_coords(med_lon, med_lat)
    projector = CoordinateProjector(epsg)

    # 2. Add Candidate Road Segments & Projection Lines
    node_lons = trip.nodes["lon"].to_numpy(dtype=float)
    node_lats = trip.nodes["lat"].to_numpy(dtype=float)
    arcs_u = trip.arcs["u"].to_numpy(dtype=int)
    arcs_v = trip.arcs["v"].to_numpy(dtype=int)

    cand_arc_ids = cands_subset["arc_id"].unique()
    for arc_id in cand_arc_ids:
        u_id = arcs_u[arc_id]
        v_id = arcs_v[arc_id]
        p1 = [node_lats[u_id], node_lons[u_id]]
        p2 = [node_lats[v_id], node_lons[v_id]]

        folium.PolyLine(
            locations=[p1, p2],
            color="#ff7f0e",  # Orange
            weight=4,
            opacity=0.7,
            popup=f"Candidate Arc: {arc_id} ({u_id} -> {v_id})",
        ).add_to(fg_candidates)

    # Projections
    if len(cands_subset) > 0 and "projected_x" in cands_subset.columns:
        cand_sample = cands_subset.iloc[:200]  # Limit lines to prevent SVG crowding
        proj_lons, proj_lats = projector.inverse(
            cand_sample["projected_x"].values, cand_sample["projected_y"].values
        )
        for i, (_, row) in enumerate(cand_sample.iterrows()):
            p_idx = int(row["point_idx"])
            gps_lat = track_subset.loc[p_idx, "lat"]
            gps_lon = track_subset.loc[p_idx, "lon"]
            proj_point = [proj_lats[i], proj_lons[i]]

            folium.PolyLine(
                locations=[[gps_lat, gps_lon], proj_point],
                color="#d62728",  # Red dashed
                weight=2,
                dash_array="4, 4",
                opacity=0.6,
                popup=f"Obs {p_idx} -> Arc {int(row['arc_id'])} (Dist: {row['distance_m']:.1f}m)",
            ).add_to(fg_projections)

    # 3. Add GPS Observations & Track Line
    gps_coords = track_subset[["lat", "lon"]].values.tolist()
    folium.PolyLine(
        locations=gps_coords,
        color="#1f77b4",  # Blue
        weight=3,
        opacity=0.85,
        popup=f"Observed GPS Track (Trip {trip.trip_id})",
    ).add_to(fg_gps_track)

    for idx, row in track_subset.iterrows():
        folium.CircleMarker(
            location=[row["lat"], row["lon"]],
            radius=4,
            color="#1f77b4",
            fill=True,
            fill_color="#1f77b4",
            fill_opacity=0.9,
            popup=f"Obs #{idx}<br>Time: {row['timestamp']:.1f}s<br>Lat: {row['lat']:.6f}<br>Lon: {row['lon']:.6f}",
        ).add_to(fg_gps_track)

    # 4. Add Ground-Truth Route (Train Only)
    if trip.partition == TRAIN_PARTITION and trip.route is not None:
        route_arc_ids = trip.route["arc_id"].values
        # Render route arcs that intersect the observed region
        route_lines = []
        for r_arc in route_arc_ids:
            if r_arc in cand_arc_ids:
                u_id = arcs_u[r_arc]
                v_id = arcs_v[r_arc]
                p1 = [node_lats[u_id], node_lons[u_id]]
                p2 = [node_lats[v_id], node_lons[v_id]]
                route_lines.append([p1, p2])

        for line in route_lines:
            folium.PolyLine(
                locations=line,
                color="#2ca02c",  # Green
                weight=5,
                opacity=0.9,
                popup="Ground-Truth Route Segment",
            ).add_to(fg_ground_truth)

    # Add all feature groups to map
    fg_network.add_to(fmap)
    fg_candidates.add_to(fmap)
    fg_projections.add_to(fmap)
    fg_ground_truth.add_to(fmap)
    fg_gps_track.add_to(fmap)

    folium.LayerControl(collapsed=False).add_to(fmap)

    # Floating HTML Legend
    legend_html = f"""
    <div style="position: fixed; 
                bottom: 30px; left: 30px; width: 260px; height: 180px; 
                background-color: white; border:2px solid #555; z-index:9999; font-size:13px;
                padding: 10px; border-radius: 6px; box-shadow: 2px 2px 8px rgba(0,0,0,0.3);">
        <b style="font-size:14px;">PathSnap Map: Trip {trip.trip_id}</b><br>
        <span style="color: #1f77b4; font-size: 16px;">&#9679;</span> GPS Observation Points<br>
        <span style="color: #1f77b4; font-weight: bold;">&mdash;</span> Observed GPS Trajectory<br>
        <span style="color: #ff7f0e; font-weight: bold;">&mdash;</span> Candidate Road Segments<br>
        <span style="color: #d62728; font-weight: bold;">- - -</span> Perpendicular Projections<br>
        <span style="color: #2ca02c; font-weight: bold;">&mdash;</span> Ground-Truth Route (Train)<br>
    </div>
    """
    fmap.get_root().html.add_child(folium.Element(legend_html))

    fmap.save(str(out_path))
    return out_path
