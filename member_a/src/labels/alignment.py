"""Training label alignment module for PathSnap.

Aligns candidate road segments with the ordered reference route sequence
using monotonic forward sequence alignment. Assigns binary classification
labels (1 for matching ground truth road segment, 0 otherwise).
Strictly isolated to training trips only.
"""

from typing import Optional, Tuple
import numpy as np
import pandas as pd
import shapely

from member_a.config.settings import TRAIN_PARTITION, TARGET_COLUMN
from member_a.src.data.loader import Trip
from member_a.src.projection.projection import project_trip


def compute_monotonic_route_alignment(
    track_x: np.ndarray,
    track_y: np.ndarray,
    node_x: np.ndarray,
    node_y: np.ndarray,
    arcs_u: np.ndarray,
    arcs_v: np.ndarray,
    route_arcs: np.ndarray,
    max_arc_forward_step: int = 5,
) -> Tuple[np.ndarray, np.ndarray]:
    """Compute optimal monotonic sequence alignment between GPS points and ordered route arcs.

    Finds the non-decreasing sequence of route indices s_0 <= s_1 <= ... <= s_{T-1}
    that minimizes the total perpendicular distance from GPS observations to route arcs.

    Parameters
    ----------
    track_x, track_y : np.ndarray
        Projected GPS observation coordinates in metric metres (length T).
    node_x, node_y : np.ndarray
        Projected road network node coordinates in metric metres.
    arcs_u, arcs_v : np.ndarray
        Road network arc endpoint node IDs.
    route_arcs : np.ndarray
        Chronological reference arc IDs (length R).
    max_arc_forward_step : int
        Maximum number of route arcs the vehicle can advance in one GPS step (default 5).

    Returns
    -------
    Tuple[np.ndarray, np.ndarray]
        - aligned_arc_ids: array of length T with the assigned ground truth arc ID for each GPS point.
        - alignment_distances: array of length T with the perpendicular distance to the assigned arc.
    """
    T = len(track_x)
    R = len(route_arcs)

    if T == 0 or R == 0:
        return np.array([], dtype=int), np.array([], dtype=float)

    # Build route arc linestrings
    r_u = arcs_u[route_arcs]
    r_v = arcs_v[route_arcs]
    r_coords = np.stack(
        [
            np.column_stack([node_x[r_u], node_y[r_u]]),
            np.column_stack([node_x[r_v], node_y[r_v]]),
        ],
        axis=1,
    )
    route_lines = shapely.linestrings(r_coords)
    gps_pts = shapely.points(track_x, track_y)

    # Compute distance matrix between GPS points and route arcs (T x R)
    dist_mat = shapely.distance(gps_pts[:, None], route_lines[None, :])

    # Dynamic Programming: monotonic progression
    cost = np.full((T, R), np.inf, dtype=float)
    backptr = np.zeros((T, R), dtype=int)

    # Initialization: allow start at any of the first few route arcs
    init_window = min(max_arc_forward_step + 1, R)
    cost[0, :init_window] = dist_mat[0, :init_window]

    for t in range(1, T):
        # Vectorized transition: for each r, find minimum previous cost in [r - max_arc_forward_step, r]
        stacked = np.full((max_arc_forward_step + 1, R), np.inf, dtype=float)
        for k in range(max_arc_forward_step + 1):
            if k == 0:
                stacked[k, :] = cost[t - 1, :]
            else:
                stacked[k, k:] = cost[t - 1, :-k]
        best_k = np.argmin(stacked, axis=0)
        cost[t, :] = np.take_along_axis(stacked, best_k[None, :], axis=0)[0] + dist_mat[t, :]
        backptr[t, :] = np.maximum(0, np.arange(R) - best_k)

    # Traceback optimal path
    best_final_r = int(np.argmin(cost[T - 1, :]))
    path = np.zeros(T, dtype=int)
    curr = best_final_r
    for t in range(T - 1, -1, -1):
        path[t] = curr
        curr = backptr[t, curr]

    aligned_arc_ids = route_arcs[path]
    alignment_distances = dist_mat[np.arange(T), path]
    return aligned_arc_ids, alignment_distances


def align_route_labels(
    trip: Trip,
    candidates: pd.DataFrame,
    override_epsg: Optional[int] = None,
) -> pd.DataFrame:
    """Assign binary target labels to candidate rows based on reference route alignment.

    This function is strictly for permitted training data. It preserves candidate row order
    and appends a binary 'label' column (1 = ground-truth road segment for that observation,
    0 = non-matching candidate).

    Parameters
    ----------
    trip : Trip
        The loaded training trip dataclass.
    candidates : pd.DataFrame
        Candidate DataFrame generated by `generate_candidates`.
    override_epsg : Optional[int]
        Optional manual EPSG code override.

    Returns
    -------
    pd.DataFrame
        Copy of candidates DataFrame with 'label' column appended.

    Raises
    ------
    PermissionError
        If called on a student_test trip (Leakage Safeguard).
    ValueError
        If trip has no reference route loaded or candidates DataFrame is invalid.
    """
    # CRITICAL LEAKAGE SAFEGUARD
    if trip.partition != TRAIN_PARTITION:
        raise PermissionError(
            f"Access Denied: Attempted to run route label alignment on partition '{trip.partition}'. "
            f"Label alignment is strictly prohibited on non-training partitions."
        )

    if trip.route is None or len(trip.route) == 0:
        raise ValueError(
            f"Trip '{trip.trip_id}' does not have a reference route loaded. "
            f"Call load_trip with include_route=True on an eligible training trip."
        )

    if candidates is None or len(candidates) == 0:
        res = candidates.copy() if candidates is not None else pd.DataFrame()
        res[TARGET_COLUMN] = np.array([], dtype=int)
        return res

    # Project trip to metric space for alignment
    proj_track, proj_nodes, epsg = project_trip(trip, override_epsg=override_epsg)

    tx = proj_track["x_m"].to_numpy(dtype=float)
    ty = proj_track["y_m"].to_numpy(dtype=float)
    nx = proj_nodes["x_m"].to_numpy(dtype=float)
    ny = proj_nodes["y_m"].to_numpy(dtype=float)
    u = trip.arcs["u"].to_numpy(dtype=int)
    v = trip.arcs["v"].to_numpy(dtype=int)
    r_arcs = trip.route["arc_id"].to_numpy(dtype=int)

    # Monotonic forward dynamic programming alignment
    aligned_arc_ids, _ = compute_monotonic_route_alignment(
        track_x=tx,
        track_y=ty,
        node_x=nx,
        node_y=ny,
        arcs_u=u,
        arcs_v=v,
        route_arcs=r_arcs,
    )

    # Assign labels to candidate rows while strictly preserving candidate row order
    out_df = candidates.copy()
    cand_pts = out_df["point_idx"].to_numpy(dtype=int)
    cand_arcs = out_df["arc_id"].to_numpy(dtype=int)

    # Map each candidate to 1 if its arc_id matches the ground-truth arc for its point_idx
    true_arcs_for_cands = aligned_arc_ids[cand_pts]
    is_positive = (cand_arcs == true_arcs_for_cands).astype(int)

    out_df[TARGET_COLUMN] = is_positive
    return out_df
